"""Pseudo-depth targets for ZipDepth's own loss (step 3, ``loss: zipdepth``).

ZipDepth is trained by distillation from Depth Anything V2 Large (its README: "pseudo depth maps
generated by Depth Anything V2 Large ... running the official inference code on the RGB images").
This script does the same on our training frames: for every list line (the middle frame of a
triplet, or the only frame of a frame list) it runs the official inference (``infer_image``: input
resized to 518 px on the short side, multiple of 14, output resized back to the frame size) on the
image the student sees (on NYU the rectified PNG when it exists, ``data.datasets.frame_path``) and
writes a 16-bit PNG to ``<data root>/pseudo_depth/<teacher>/<frame path>.png``.

The PNG stores the relative inverse depth divided by its per-image maximum (x 65535). ZipDepthLoss
normalises the target by median and mean absolute deviation, so the per-image scale is irrelevant.

Inference is fp32 on every GPU, so the targets do not depend on the machine. Existing outputs are
skipped (atomic writes), so an interrupted run resumes by re-running the same command.

    # weights (1.34 GB, CC-BY-NC-4.0) are downloaded once to <cache root>/dav2/ if missing
    python scripts/make_pseudo_depth.py --dataset nyu --list splits/nyu_raw_triplets_train.txt
    python scripts/make_pseudo_depth.py --dataset nyu --list splits/nyu_raw_triplets_train.txt --limit 200   # timing
"""
from __future__ import annotations

import argparse
import os
import sys
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from data.datasets import frame_path, pseudo_depth_path, read_list, target_frame  # noqa: E402
from sota.loader import load_depth_anything_v2  # noqa: E402
from utils import paths  # noqa: E402
from utils.device import pick_device  # noqa: E402

WEIGHTS_URL = "https://huggingface.co/depth-anything/Depth-Anything-V2-{size}/resolve/main/depth_anything_v2_{enc}.pth"
SIZES = {"vits": "Small", "vitb": "Base", "vitl": "Large"}


def default_weights(encoder: str) -> Path:
    return paths.cache_root() / "dav2" / f"depth_anything_v2_{encoder}.pth"


def build_teacher(encoder: str, weights: Path | None, device: torch.device) -> torch.nn.Module:
    """Depth Anything V2 in eval mode; ``weights=None`` keeps the random init (tests only)."""
    model = load_depth_anything_v2(encoder)
    if weights is not None:
        if not weights.exists():
            weights.parent.mkdir(parents=True, exist_ok=True)
            url = WEIGHTS_URL.format(size=SIZES[encoder], enc=encoder)
            print(f"[dav2] downloading {url} -> {weights}")
            torch.hub.download_url_to_file(url, str(weights))
        model.load_state_dict(torch.load(weights, map_location="cpu", weights_only=True), strict=True)
    return model.to(device).eval()


@torch.no_grad()
def infer(model: torch.nn.Module, rgb: np.ndarray, input_size: int, device: torch.device) -> np.ndarray:
    """``DepthAnythingV2.infer_image`` on an explicit device: (H, W) RGB uint8 -> (H, W) relative inverse depth."""
    bgr = np.ascontiguousarray(rgb[..., ::-1])
    image, (h, w) = model.image2tensor(bgr, input_size)
    depth = model(image.to(device))
    return F.interpolate(depth[:, None], (h, w), mode="bilinear", align_corners=True)[0, 0].float().cpu().numpy()


def to_png16(disp: np.ndarray) -> np.ndarray:
    """Relative inverse depth -> uint16, divided by its maximum (all zeros stay zeros)."""
    disp = np.clip(disp, 0.0, None)
    m = float(disp.max())
    return np.zeros(disp.shape, np.uint16) if m <= 0 else np.round(disp / m * 65535.0).astype(np.uint16)


def frames_of(lists: list[Path]) -> list[str]:
    seen, out = set(), []
    for lst in lists:
        for tokens in read_list(lst):
            rel = target_frame(tokens)
            if rel not in seen:
                seen.add(rel)
                out.append(rel)
    return out


def run(dataset: str, lists: list[Path], teacher: str = "dav2_vitl", encoder: str = "vitl",
        weights: Path | None = None, input_size: int = 518, device: str = "auto",
        limit: int | None = None, overwrite: bool = False, log_every: int = 100) -> dict:
    root = paths.data_root()
    dev = pick_device(device)
    todo = frames_of(lists)
    if not overwrite:
        todo = [r for r in todo if not pseudo_depth_path(root, teacher, r).exists()]
    if limit is not None:
        todo = todo[:limit]
    print(f"[pseudo-depth] {teacher} ({encoder}, input {input_size}) on {dev}: {len(todo)} frames to write")
    if not todo:
        return {"written": 0, "seconds": 0.0}
    model = build_teacher(encoder, weights, dev)
    t0 = time.time()
    for i, rel in enumerate(todo, 1):
        rgb = np.asarray(Image.open(frame_path(root, rel, dataset)).convert("RGB"))
        out = pseudo_depth_path(root, teacher, rel)
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_name(out.stem + ".tmp.png")
        Image.fromarray(to_png16(infer(model, rgb, input_size, dev))).save(tmp)
        os.replace(tmp, out)
        if i % log_every == 0 or i == len(todo):
            s = time.time() - t0
            print(f"[pseudo-depth] {i}/{len(todo)} | {i / s:.2f} frames/s | eta {(len(todo) - i) * s / i / 3600:.2f} h")
    return {"written": len(todo), "seconds": time.time() - t0}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True, choices=["nyu", "kitti"])
    ap.add_argument("--list", action="append", required=True,
                    help="list file (triplets or frames), relative to the data root; repeatable")
    ap.add_argument("--encoder", default="vitl", choices=sorted(SIZES))
    ap.add_argument("--teacher", default=None, help="output folder name (default dav2_<encoder>)")
    ap.add_argument("--weights", type=Path, default=None, help="default <cache root>/dav2/depth_anything_v2_<encoder>.pth")
    ap.add_argument("--input-size", type=int, default=518)
    ap.add_argument("--device", default="auto")
    ap.add_argument("--limit", type=int, default=None, help="write at most N frames (to time a run)")
    ap.add_argument("--overwrite", action="store_true")
    args = ap.parse_args(argv)
    lists = [p if p.is_absolute() else paths.data_root() / p for p in map(Path, args.list)]
    res = run(args.dataset, lists, teacher=args.teacher or f"dav2_{args.encoder}", encoder=args.encoder,
              weights=args.weights or default_weights(args.encoder), input_size=args.input_size,
              device=args.device, limit=args.limit, overwrite=args.overwrite)
    print(f"[pseudo-depth] done: {res['written']} frames in {res['seconds'] / 3600:.2f} h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
